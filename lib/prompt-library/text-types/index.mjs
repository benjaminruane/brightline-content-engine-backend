export const TEXT_TYPE_MODULES = {
  NEW_DIRECT_INVESTMENT,
  ADD_ON_DIRECT_INVESTMENT,
  DIRECT_INVESTMENT_EXIT,
  DIRECT_INVESTMENT_REVALUATION,
  NEW_SECONDARY_INVESTMENT,
  NEW_PRIMARY_COMMITMENT,
  FUND_CAPITAL_CALL,
  FUND_DISTRIBUTION,
  FUND_REVALUATION,
  SPECIAL_TOPIC,
  GENERAL,
};

export function textTypeModule(eventType) {
  if (typeof eventType !== "string" || !eventType) return null;
  if (eventType === "NEW_FUND_COMMITMENT") return TEXT_TYPE_MODULES.NEW_PRIMARY_COMMITMENT;
  return TEXT_TYPE_MODULES[eventType] || null;
}
